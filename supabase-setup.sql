create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select auth.uid() is not null
     and exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

create or replace function public.is_volunteer()
returns boolean language sql stable security definer set search_path = public as $$
  select auth.uid() is not null
     and exists (select 1 from public.volunteers where user_id = auth.uid() and active);
$$;

create or replace function public.is_reviewer()
returns boolean language sql stable security definer set search_path = public as $$
  select public.is_admin() or public.is_volunteer();
$$;

create or replace function public.has_approved_channel(p_user uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select p_user is not null
     and exists (select 1 from public.channels where user_id = p_user and status = 'approved');
$$;

create or replace function public.required_approvals()
returns integer language sql stable security definer set search_path = public as $$
  select coalesce((select required_volunteer_approvals from public.review_settings where id = 1), 1);
$$;

-- عدد موافقات المتطوعين (لا يُحتسب تصويت صاحب التلاوة)
create or replace function public.volunteer_approvals(p_video_id text)
returns integer language sql stable security definer set search_path = public as $$
  select count(*)::int
  from public.video_reviews r
  join public.videos v on v.id = r.video_id
  where v.id::text = p_video_id
    and r.decision = 'approve'
    and r.reviewer_role = 'volunteer'
    and r.reviewer_id is distinct from v.user_id;
$$;

create or replace function public.my_roles()
returns json language sql stable security definer set search_path = public as $$
  select json_build_object(
    'user_id',            auth.uid(),
    'is_admin',           public.is_admin(),
    'is_volunteer',       public.is_volunteer(),
    'has_channel',        public.has_approved_channel(auth.uid()),
    'required_approvals', public.required_approvals()
  );
$$;

