create or replace function public.videos_before_insert()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  -- التشغيل من لوحة Supabase أو بالمفتاح السري يتجاوز هذا الفحص
  if auth.uid() is null then
    new.status := coalesce(new.status, 'pending');
    return new;
  end if;

  new.user_id      := auth.uid();
  new.status       := case when new.status = 'draft' then 'draft' else 'pending' end;
  new.review_note  := null;
  new.reviewed_by  := null;
  new.reviewed_at  := null;
  new.published_at := null;
  new.created_at   := now();
  new.view_count   := 0;
  return new;
end $$;

create or replace function public.videos_before_update()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_admin   boolean := public.is_admin();
  v_changed boolean;
  v_count   integer;
  v_needed  integer;
begin
  if auth.uid() is null then
    return new;
  end if;

  new.updated_at := now();

  -- عدّاد المشاهدات لا يتغير إلا عبر الدالة record_view
  if coalesce(current_setting('tibyan.counting', true), '') <> '1' then
    new.view_count := old.view_count;
  end if;

  -- حقول المراجعة لا يغيّرها إلا مسار القرار أدناه
  if not v_admin then
    new.user_id     := old.user_id;
    new.review_note := old.review_note;
  end if;
  new.reviewed_by  := old.reviewed_by;
  new.reviewed_at  := old.reviewed_at;
  new.published_at := old.published_at;

  v_changed :=
    (new.title, new.reader_name, new.category, new.description, new.video_url, new.thumbnail_url)
    is distinct from
    (old.title, old.reader_name, old.category, old.description, old.video_url, old.thumbnail_url);

  -- أي تعديل على المحتوى يعيد التلاوة إلى المراجعة من جديد
  if v_changed then
    new.status       := case when new.status = 'draft' then 'draft' else 'pending' end;
    new.published_at := null;
    new.reviewed_by  := null;
    new.reviewed_at  := null;
    new.review_note  := null;
    delete from public.video_reviews where video_id = old.id;
    return new;
  end if;

  if new.status is distinct from old.status then
    if new.status = 'published' then
      if not v_admin then
        raise exception 'النشر متاح لإدارة تِبيان فقط بعد المراجعة.';
      end if;
      if old.status <> 'pending' then
        raise exception 'لا يمكن نشر تلاوة ليست قيد المراجعة.';
      end if;
      v_count  := public.volunteer_approvals(old.id::text);
      v_needed := public.required_approvals();
      if v_count < v_needed then
        raise exception 'لا يمكن النشر قبل اكتمال موافقات المتطوعين (% من %).', v_count, v_needed;
      end if;
      new.published_at := now();
      new.reviewed_by  := auth.uid();
      new.reviewed_at  := now();

    elsif new.status = 'rejected' then
      if not v_admin then
        raise exception 'الرفض النهائي متاح لإدارة تِبيان فقط.';
      end if;
      new.published_at := null;
      new.reviewed_by  := auth.uid();
      new.reviewed_at  := now();

    elsif new.status = 'pending' then
      if old.status = 'published' and not v_admin then
        raise exception 'لا يمكن إعادة تلاوة منشورة إلى المراجعة إلا من الإدارة.';
      end if;
      -- إعادة الإرسال تبدأ مراجعة جديدة
      new.published_at := null;
      if not v_admin then new.review_note := null; end if;
      delete from public.video_reviews where video_id = old.id;

    elsif new.status = 'draft' then
      new.published_at := null;
    end if;
  end if;

  return new;
end $$;

create trigger videos_before_insert_trg
  before insert on public.videos
  for each row execute function public.videos_before_insert();

create trigger videos_before_update_trg
  before update on public.videos
  for each row execute function public.videos_before_update();

