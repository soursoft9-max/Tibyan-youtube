-- صاحب القناة يعدّل الوصف والصور والمعرّف فقط؛ الاسم والحالة للإدارة
create or replace function public.channels_before_update()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null or public.is_admin() then
    return new;
  end if;
  new.user_id      := old.user_id;
  new.status       := old.status;
  new.channel_name := old.channel_name;
  if new.handle is not null then
    new.handle := lower(trim(new.handle));
    if new.handle = '' then
      new.handle := null;
    elsif new.handle !~ '^[a-z0-9_.-]{3,30}$' then
      raise exception 'المعرّف من 3 إلى 30 حرفًا: أحرف إنجليزية صغيرة أو أرقام أو _ . -';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists channels_before_update_trg on public.channels;
create trigger channels_before_update_trg
  before update on public.channels
  for each row execute function public.channels_before_update();

-- تسجيل مشاهدة (للتلاوات المنشورة فقط) وإضافتها إلى سجل المستخدم
create or replace function public.record_view(p_video_id text)
returns void language plpgsql security definer set search_path = public as $$
declare v_id public.videos.id%type;
begin
  select id into v_id from public.videos where id::text = p_video_id and status = 'published';
  if not found then return; end if;

  perform set_config('tibyan.counting', '1', true);
  update public.videos set view_count = view_count + 1 where id = v_id;
  perform set_config('tibyan.counting', '0', true);

  if auth.uid() is not null then
    insert into public.watch_history (user_id, video_id, watched_at)
    values (auth.uid(), v_id, now())
    on conflict (user_id, video_id) do update set watched_at = now();
  end if;
end $$;

-- إحصاءات القنوات: المشتركون والتلاوات والمشاهدات
create or replace function public.channel_stats(p_ids text[])
returns table (channel_id text, subscribers bigint, videos bigint, views bigint)
language sql stable security definer set search_path = public as $$
  select c.id::text,
         (select count(*) from public.subscriptions s where s.channel_id = c.id),
         (select count(*) from public.videos v where v.user_id = c.user_id and v.status = 'published'),
         (select coalesce(sum(v.view_count), 0) from public.videos v
           where v.user_id = c.user_id and v.status = 'published')::bigint
  from public.channels c
  where c.id::text = any(p_ids)
    and (c.status = 'approved' or c.user_id = auth.uid() or public.is_admin());
$$;

-- حالة صفحة المشاهدة في طلب واحد
create or replace function public.watch_state(p_video_id text)
returns json language plpgsql stable security definer set search_path = public as $$
declare
  v_id     public.videos.id%type;
  v_owner  uuid;
  v_status text;
  channel  json := null;
  c_id     public.channels.id%type;
  c_name   text; c_avatar text; c_handle text;
begin
  select id, user_id, status into v_id, v_owner, v_status
  from public.videos where id::text = p_video_id;
  if not found then return null; end if;
  if v_status <> 'published' and v_owner is distinct from auth.uid() and not public.is_reviewer() then
    return null;
  end if;

  select id, channel_name, avatar_url, handle into c_id, c_name, c_avatar, c_handle
  from public.channels where user_id = v_owner and status = 'approved'
  order by created_at limit 1;

  if found then
    channel := json_build_object(
      'id', c_id, 'name', c_name, 'avatar_url', c_avatar, 'handle', c_handle,
      'subscribers', (select count(*) from public.subscriptions where channel_id = c_id),
      'subscribed', exists (select 1 from public.subscriptions where channel_id = c_id and user_id = auth.uid()),
      'is_mine', v_owner = auth.uid());
  end if;

  return json_build_object(
    'likes',    (select count(*) from public.video_likes where video_id = v_id),
    'liked',    exists (select 1 from public.video_likes where video_id = v_id and user_id = auth.uid()),
    'saved',    exists (select 1 from public.watch_later where video_id = v_id and user_id = auth.uid()),
    'comments', (select count(*) from public.comments where video_id = v_id),
    'channel',  channel);
end $$;

-- التعليقات مع اسم الكاتب (اسم قناته أو اسمه في الملف الشخصي)
create or replace function public.get_comments(p_video_id text)
returns table (id bigint, parent_id bigint, body text, created_at timestamptz, user_id uuid,
               author_name text, author_channel_id text, author_avatar text,
               is_creator boolean, can_delete boolean)
language sql stable security definer set search_path = public as $$
  select cm.id, cm.parent_id, cm.body, cm.created_at, cm.user_id,
         coalesce(ch.channel_name, nullif(trim(p.display_name), ''), 'مستخدم تِبيان'),
         ch.id::text, ch.avatar_url,
         coalesce(cm.user_id = v.user_id, false),
         coalesce(cm.user_id = auth.uid() or v.user_id = auth.uid() or public.is_reviewer(), false)
  from public.comments cm
  join public.videos v on v.id = cm.video_id
  left join lateral (
    select c.id, c.channel_name, c.avatar_url from public.channels c
    where c.user_id = cm.user_id and c.status = 'approved' limit 1
  ) ch on true
  left join public.profiles p on p.user_id = cm.user_id
  where v.id::text = p_video_id
    and (v.status = 'published' or v.user_id = auth.uid() or public.is_reviewer())
  order by cm.created_at desc
  limit 500;
$$;

-- القرّاء: الأسماء الموجودة في التلاوات المنشورة مع عددها ومشاهداتها
create or replace function public.reader_stats()
returns table (reader_name text, videos bigint, views bigint)
language sql stable security definer set search_path = public as $$
  select trim(reader_name), count(*), coalesce(sum(view_count), 0)::bigint
  from public.videos
  where status = 'published' and coalesce(trim(reader_name), '') <> ''
  group by trim(reader_name)
  order by count(*) desc, 1;
$$;

