  execute format($f$
    create table if not exists public.video_reviews (
      id            bigint generated by default as identity primary key,
      video_id      %s not null references public.videos(id) on delete cascade,
      reviewer_id   uuid not null references auth.users(id) on delete cascade,
      reviewer_role text not null check (reviewer_role in ('volunteer', 'admin')),
      decision      text not null check (decision in ('approve', 'reject')),
      notes         text,
      created_at    timestamptz not null default now(),
      updated_at    timestamptz not null default now(),
      unique (video_id, reviewer_id)
    )$f$, id_type);
end $$;

